def test_F24_permission_failure_preserves_source(case):
    case.write('source/report.txt', 'source must survive')
    case.mkdir('locked')
    case.mkdir('writable')
    case.desktop.call('chmod', path=case.path('locked'), mode=0o555)
    case.launch('files', case.path('source'))
    case.select('source/report.txt')
    case.key('ctrl+c')
    case.navigate('locked')
    case.expect('locked', 'button')
    case.key('ctrl+v')
    case.expect(contains='1 failed', role='notification')
    case.expect_file('source/report.txt', 'source must survive')
    case.expect_file('locked/report.txt', exists=False)
    case.navigate('writable')
    case.expect('writable', 'button')
    case.key('ctrl+v')
    case.expect('report.txt')
    case.expect_file('writable/report.txt', 'source must survive')


