def test_F07_copy_then_move_through_desktop_clipboard(case):
    case.write('inbox/report.txt', 'payload to preserve')
    case.write('inbox/nested/empty.txt', '')
    case.mkdir('destination')
    case.mkdir('archive')
    case.launch('files', case.path('inbox'))
    case.expect('report.txt')
    case.key('ctrl+a')
    case.key('ctrl+c')
    case.navigate('destination')
    case.expect('destination', 'button')
    case.key('ctrl+v')
    case.expect('report.txt')
    case.expect_file('destination/report.txt', 'payload to preserve')
    case.expect_file('destination/nested/empty.txt', '')
    case.expect_file('inbox/report.txt', 'payload to preserve')
    case.expect_file('inbox/nested/empty.txt', '')
    case.key('ctrl+a')
    case.key('ctrl+x')
    case.navigate('archive')
    case.expect('archive', 'button')
    case.key('ctrl+v')
    case.expect('report.txt')
    case.expect_file('archive/report.txt', 'payload to preserve')
    case.expect_file('archive/nested/empty.txt', '')
    case.expect_file('destination/report.txt', exists=False)
    case.expect_file('destination/nested', exists=False)


