def test_F17_picker_returns_selected_path(case):
    case.write('attachment.txt', 'attachment')
    case.launch('files', '--pick-file', case.work)
    case.select('attachment.txt')
    case.key('enter')
    from driver import eventually
    eventually(lambda: case.desktop.call('alive', pid=case.pid), lambda alive: not alive, 'picker exits')
    result = json.loads(case.desktop.read(case.root + f'/logs/{case.label}.stdout'))
    assert result == {'path': case.path('attachment.txt'), 'read_only': False, 'filter_index': 0}
    case.expect_exit(0)
    case.expect_file('attachment.txt', 'attachment')


