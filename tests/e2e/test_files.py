def test_F01_navigation_and_history(case):
    case.write('inbox/report.txt', 'report\n')
    case.write('destination/receipt.txt', 'receipt\n')
    case.launch('files', case.work)
    case.select('inbox')
    case.key('enter')
    case.expect('report.txt')
    case.key('alt+up')
    case.expect('destination')
    case.navigate('destination')
    case.expect('receipt.txt')
    case.key('alt+left')
    case.expect('inbox')
    case.key('alt+right')
    case.expect('receipt.txt')
    case.expect_file('inbox/report.txt', 'report\n')


